import { config } from './config.js';
import { openDatabase,createStore } from './database.js';
import { createOllama } from './ollama.js';
import { createApp } from './app.js';
if(!['127.0.0.1','localhost','::1'].includes(config.host))throw Error('HOST must be a loopback address. This is a single-profile local backend.');
const store=createStore(openDatabase(config.databasePath));
const app=createApp({store,ollama:createOllama(config),config});
const server=app.listen(config.port,config.host,()=>{console.log(`BreakTrail API: http://localhost:${config.port}/api`);console.log(`SQLite: ${config.databasePath}`);console.log(`Ollama: ${config.ollamaUrl} | model: ${config.model}`);console.log(`Fallback: ${config.allowFallback?'enabled and explicitly labeled':'disabled (strict AI)'}`)});
server.on('error',err=>{store.close();console.error(err.message);process.exitCode=1});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>{server.close(()=>{store.close();process.exit(0)});setTimeout(()=>process.exit(1),5000).unref()});
